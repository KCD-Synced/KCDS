"""Builds the local character's monologue lines from a game installation.

The game voices a remark of the player's character (a horse command, a photo-mode comment, a
hunger bark) by asking the dialogue system for a metarole; the dialogue system then picks one line
of that metarole's pool. KCDS keeps the request from reaching the dialogue system (the monologue
is Henry's voice whoever plays) and raises monologueSuppressed with one line of the same pool.

- roles: the roles Libs/Storm/roles/dude.xml (IPL_GameData.pak) gives the player, the rules whose
  selectors name the player (isPlayer, isPlayerHenry).
- lines: the "ingame monolog" dialogues of Scripts.pak (Quests/**.xml), each Response of a player
  role with its spoken text's StringName, which is the line's localization key
  (Localization/*_xml.pak text_ui_dialog.xml).

    python Dev/tools/monologue/build_monologue_lines.py "<game folder>"

writes Client/runtime/hud/monologue_lines.inc: { "METAROLE", "key1|key2|..." } entries, sorted, the
keys as adjacent literals of four.
"""

import argparse
import xml.etree.ElementTree as ElementTree
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUTPUT = ROOT / "Client" / "runtime" / "hud" / "monologue_lines.inc"
PLAYER_SELECTORS = ("isPlayer", "isPlayerHenry")
KEYS_PER_LINE = 4


def player_roles(game):
    with zipfile.ZipFile(game / "Data" / "IPL_GameData.pak") as pak:
        root = ElementTree.fromstring(pak.read("Libs/Storm/roles/dude.xml"))
    roles = set()
    for rule in root.iter("rule"):
        selectors = rule.find("selectors")
        if selectors is None:
            continue
        if not any(selectors.find(name) is not None for name in PLAYER_SELECTORS):
            continue
        for role in rule.iter("addRole"):
            if role.get("name"):
                roles.add(role.get("name"))
    return roles


def monologue_lines(game, roles):
    lines = {}
    with zipfile.ZipFile(game / "Data" / "Scripts.pak") as pak:
        for name in pak.namelist():
            if not name.startswith("Quests/") or not name.lower().endswith(".xml"):
                continue
            data = pak.read(name)
            if b"ingame monolog" not in data:
                continue
            try:
                root = ElementTree.fromstring(data)
            except ElementTree.ParseError:
                continue
            for dialogue in root.iter("Dialogue"):
                if dialogue.get("Type") != "ingame monolog":
                    continue
                for response in dialogue.iter("Response"):
                    role = response.get("Role")
                    text = response.find("Text")
                    if role not in roles or text is None or not text.get("StringName"):
                        continue
                    lines.setdefault(role, set()).add(text.get("StringName"))
    return lines


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("game", help="the game's installation folder")
    args = parser.parse_args()
    game = Path(args.game)
    lines = monologue_lines(game, player_roles(game))
    out = [
        "// Generated by Dev/tools/monologue/build_monologue_lines.py from the game's own data:",
        "// the player's monologue metaroles and their lines' localization keys.",
    ]
    for role in sorted(lines):
        # Adjacent literals of a few keys each: MSVC takes at most 16 KB in one literal.
        keys = sorted(lines[role])
        out.append(f'{{"{role}",')
        for start in range(0, len(keys), KEYS_PER_LINE):
            chunk = "|".join(keys[start : start + KEYS_PER_LINE])
            separator = "|" if start + KEYS_PER_LINE < len(keys) else ""
            out.append(f'    "{chunk}{separator}"')
        out.append("},")
    OUTPUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUTPUT}: {len(lines)} metaroles, {sum(len(v) for v in lines.values())} lines")


if __name__ == "__main__":
    main()
