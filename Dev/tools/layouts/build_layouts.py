"""Writes the game's memory layouts the client reads from one schema file.

Dev/tools/layouts/game_layouts.json names, for each of the game's objects the client reads, the
fields it reads: their offset in bytes, their type and what they hold. A game patch that moves a
field is fixed there, once, instead of in every file that reads it. This writes
Client/runtime/core/game_layouts.hpp from it:

    python Dev/tools/layouts/build_layouts.py           writes the header
    python Dev/tools/layouts/build_layouts.py --check   fails when the header is not up to date

Each struct becomes a namespace of constants (layouts::Actor::kSoul) with its fields' sizes, and
the header checks at compile time that no two fields of a struct overlap and that every field lies
inside the struct's size where the schema gives one.
"""

import json
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SCHEMA = ROOT / "Dev/tools/layouts/game_layouts.json"
HEADER = ROOT / "Client/runtime/core/game_layouts.hpp"

SIZES = {"pointer": 8, "float": 4, "u8": 1, "u16": 2, "u32": 4, "i32": 4, "u64": 8, "guid": 16}


def field_size(name, field):
    if field["type"] == "bytes":
        return field["size"]
    if field["type"] not in SIZES:
        raise SystemExit(f"{name}: unknown type {field['type']}")
    return SIZES[field["type"]]


def comment(text):
    """`text` as // lines of at most 100 columns, as clang-format wraps them."""
    return textwrap.wrap(text, width=100, initial_indent="// ", subsequent_indent="// ")


def static_assert(condition, message):
    """A static_assert on one line, or with its message on the next as clang-format breaks it."""
    line = f'static_assert({condition}, "{message}");'
    if len(line) <= 100:
        return [line]
    return [f"static_assert({condition},", f'              "{message}");']


def render(schema):
    out = [
        "// Generated by Dev/tools/layouts/build_layouts.py from Dev/tools/layouts/game_layouts.json;",
        "// change the schema and run the script, never this file.",
        "//",
        *comment(schema["about"]),
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "namespace kcds::layouts {",
    ]
    for struct_name, struct in schema["structs"].items():
        out.append("")
        out.extend(comment(struct["about"]))
        out.append(f"namespace {struct_name} {{")
        fields = sorted(struct["fields"].items(), key=lambda item: item[1]["offset"])
        for name, field in fields:
            size = field_size(f"{struct_name}.{name}", field)
            out.extend(comment(f"{field['about']} ({field['type']}, {size} bytes)"))
            out.append(f"inline constexpr std::size_t k{name} = {field['offset']};")
            out.append(f"inline constexpr std::size_t k{name}Size = {size};")
        if "size" in struct:
            out.append(f"inline constexpr std::size_t kSize = {struct['size']};")
        out.append(f"}}  // namespace {struct_name}")
        # A block of bytes may hold other fields (Soul.Properties holds Soul.Health); any other
        # field ends before the next one starts.
        for (name, field), (next_name, _) in zip(fields, fields[1:]):
            if field["type"] == "bytes":
                continue
            out.extend(
                static_assert(
                    f"{struct_name}::k{name} + {struct_name}::k{name}Size <= "
                    f"{struct_name}::k{next_name}",
                    f"{struct_name}.{name} overlaps {next_name}",
                )
            )
        if "size" in struct:
            last_name = fields[-1][0]
            out.extend(
                static_assert(
                    f"{struct_name}::k{last_name} + {struct_name}::k{last_name}Size <= "
                    f"{struct_name}::kSize",
                    f"{struct_name}.{last_name} lies past the end",
                )
            )
    # Facts between structs (one field is another's block plus an offset).
    if schema.get("checks"):
        out.append("")
    for check in schema.get("checks", []):
        out.extend(static_assert(check["condition"], check["about"]))
    out.append("")
    out.append("}  // namespace kcds::layouts")
    out.append("")
    return "\n".join(out)


def main():
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    text = render(schema)
    if "--check" in sys.argv[1:]:
        current = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
        if current != text:
            raise SystemExit(f"{HEADER} is not up to date: run {Path(__file__).name}")
        return
    HEADER.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {HEADER}")


if __name__ == "__main__":
    main()
