"""The Asset/Animation Studio's floor as a C++ header the game client embeds.

The level's terrain floor is not drawn in some starts (its physics stands), so the studio draws a
floor of its own: a flat square of FLOOR_SIZE metres at FLOOR_HEIGHT (a centimetre above the
terrain), in TILES x TILES quads, each repeating the game's own cobblestone texture (the one the
level's terrain layer uses, textures/terrain/cobblestones/cobble_stones_c_4x4) every TEXTURE_METRES.
It has no physics: the terrain's carries the character.

The game client mounts the .cgf and the .mtl from memory (native_ui mount_files) at
objects/kcds_studio/floor and shows it as a static mesh (studio/studio_floor.hpp).

    python make_studio_floor.py <out header>
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "blender"))

import kcds_cgf  # noqa: E402

FLOOR_SIZE = 128.0
FLOOR_HEIGHT = 32.01
TILES = 16
TEXTURE_METRES = 4.0
MATERIAL_FILE = "objects/kcds_studio/floor"


def floor_mesh():
    mesh = kcds_cgf.Mesh()
    step = FLOOR_SIZE / TILES
    repeats = step / TEXTURE_METRES
    across = (1.0, 0.0, 0.0)
    up = (0.0, 1.0, 0.0)
    for row in range(TILES):
        for column in range(TILES):
            first = len(mesh.positions)
            x = column * step
            y = row * step
            corners = ((0, 0), (1, 0), (1, 1), (0, 1))
            for cu, cv in corners:
                mesh.positions.append((x + cu * step, y + cv * step, FLOOR_HEIGHT))
                mesh.uvs.append((cu * repeats, (1 - cv) * repeats))
                mesh.tangents.append((across, up, 1))
            mesh.indices += [first, first + 1, first + 2, first, first + 2, first + 3]
    mesh.subsets.append(kcds_cgf.Subset(0, len(mesh.indices), 0, len(mesh.positions), 0))
    mesh.materials.append("kcds_floor")
    mesh.physicalize.append(kcds_cgf.PHYSICALIZE_NONE)
    return mesh


def floor_material():
    return (
        '<Material MtlFlags="524544" vertModifType="0">\n'
        "  <SubMaterials>\n"
        '    <Material Name="kcds_floor" MtlFlags="524416" Shader="Illum" '
        'GenMask="20000000000000" StringGenMask="" SurfaceType="mat_rock" Diffuse="1,1,1" '
        'Specular="0.04,0.04,0.04" Opacity="1" Shininess="10" vertModifType="0" LayerAct="1">\n'
        "      <Textures>\n"
        '        <Texture Map="Diffuse" '
        'File="textures/terrain/cobblestones/cobble_stones_c_4x4_diff.dds" />\n'
        "      </Textures>\n"
        "    </Material>\n"
        "  </SubMaterials>\n"
        "</Material>\n"
    )


def as_array(name, data):
    lines = [f"inline constexpr unsigned char {name}[] = {{"]
    for start in range(0, len(data), 20):
        lines.append("    " + ", ".join(str(byte) for byte in data[start : start + 20]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    model = kcds_cgf.write_cgf(floor_mesh(), MATERIAL_FILE, "kcds_floor")
    material = floor_material().encode("ascii")
    header = "\n".join(
        [
            "// Generated by Dev/tools/assets/kcds_studio/make_studio_floor.py: the studio's floor.",
            "#pragma once",
            "",
            "namespace kcds::runtime::studio::floor_files {",
            "",
            as_array("kModel", model),
            "",
            as_array("kMaterial", material),
            "",
            "}  // namespace kcds::runtime::studio::floor_files",
            "",
        ]
    )
    os.makedirs(os.path.dirname(os.path.abspath(sys.argv[1])), exist_ok=True)
    with open(sys.argv[1], "w", encoding="ascii") as file:
        file.write(header)


if __name__ == "__main__":
    main()
