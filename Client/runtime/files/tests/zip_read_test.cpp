KCD2S_TEST(zip_read, fixed_dynamic_and_stored_deflate_blocks_inflate) {
  const std::vector<std::uint8_t> fixed = {0xcb, 0x48, 0xcd, 0xc9, 0xc9,
                                           0x57, 0xc8, 0x40, 0x27, 0x01};
  const auto hello = files::inflate(fixed.data(), fixed.size(), 23);
  KCD2S_CHECK(hello.has_value());
  KCD2S_CHECK_EQ(text_of(*hello), std::string("hello hello hello hello"));

  const auto dynamic = files::inflate(kDynamic.data(), kDynamic.size(), 1036);
  KCD2S_CHECK(dynamic.has_value());
  KCD2S_CHECK_EQ(files::zip_crc32(dynamic->data(), dynamic->size()), 0x21b76eb4u);

  const std::vector<std::uint8_t> stored = {0x01, 0x07, 0x00, 0xf8, 0xff, 0x73,
                                            0x74, 0x6f, 0x72, 0x65, 0x64, 0x21};
  const auto plain = files::inflate(stored.data(), stored.size(), 7);
  KCD2S_CHECK(plain.has_value());
  KCD2S_CHECK_EQ(text_of(*plain), std::string("stored!"));
}

KCD2S_TEST(zip_read, wrong_sizes_and_broken_data_are_refused) {
  const std::vector<std::uint8_t> fixed = {0xcb, 0x48, 0xcd, 0xc9, 0xc9,
                                           0x57, 0xc8, 0x40, 0x27, 0x01};
  KCD2S_CHECK(!files::inflate(fixed.data(), fixed.size(), 22).has_value());
  KCD2S_CHECK(!files::inflate(fixed.data(), fixed.size(), 24).has_value());
  KCD2S_CHECK(!files::inflate(fixed.data(), 5, 23).has_value());
  // Block type 3 does not exist.
  const std::vector<std::uint8_t> reserved = {0x07, 0x00};
  KCD2S_CHECK(!files::inflate(reserved.data(), reserved.size(), 1).has_value());
}

KCD2S_TEST(zip_read, a_zip_lists_its_entries_and_gives_their_bytes) {
  const auto read = files::zip_in_memory(kZip);
  const auto entries = files::zip_entries(read, kZip.size());
  KCD2S_CHECK(entries.has_value());
  KCD2S_CHECK_EQ(entries->size(), std::size_t(2));
  KCD2S_CHECK_EQ((*entries)[0].name, std::string("Tables/a.xml"));
  KCD2S_CHECK_EQ((*entries)[0].method, std::uint16_t(8));
  KCD2S_CHECK_EQ((*entries)[1].name, std::string("b.txt"));
  const auto table = files::zip_entry_bytes(read, (*entries)[0]);
  KCD2S_CHECK(table.has_value());
  KCD2S_CHECK_EQ(text_of(*table), "<a>" + std::string(300, 'x') + "</a>");
  const auto plain = files::zip_entry_bytes(read, (*entries)[1]);
  KCD2S_CHECK(plain.has_value());
  KCD2S_CHECK_EQ(text_of(*plain), std::string("plain"));

  // A changed byte fails the CRC.
  std::vector<std::uint8_t> changed = kZip;
  changed[91] = 'P';
  const auto changed_read = files::zip_in_memory(changed);
  KCD2S_CHECK(!files::zip_entry_bytes(changed_read, (*entries)[1]).has_value());
  // No end record: no entries.
  const std::vector<std::uint8_t> cut(kZip.begin(), kZip.begin() + 100);
  KCD2S_CHECK(!files::zip_entries(files::zip_in_memory(cut), cut.size()).has_value());
}

KCD2S_TEST(zip_read, stored_zips_read_back_entry_for_entry) {
  const std::vector<std::pair<std::string, std::vector<std::uint8_t>>> written = {
      {"levelinfo.xml", {'<', 'L', '/', '>'}},
      {"shaderslist.txt", {}},
      {"terrain/indoor.dat", {6, 0, 0, 0, 20, 0, 0, 0}},
  };
  const std::vector<std::uint8_t> zip = files::stored_zip_entries(written);
  const auto read = files::zip_in_memory(zip);
  const auto entries = files::zip_entries(read, zip.size());
  KCD2S_CHECK(entries.has_value());
  KCD2S_CHECK_EQ(entries->size(), written.size());
  for (std::size_t index = 0; index < written.size(); ++index) {
    KCD2S_CHECK_EQ((*entries)[index].name, written[index].first);
    const auto bytes = files::zip_entry_bytes(read, (*entries)[index]);
    KCD2S_CHECK(bytes.has_value());
    KCD2S_CHECK(*bytes == written[index].second);
  }
}
